-- ---- overdue: one urgent mail per due date (hourly)

create or replace function public.check_incident_due() returns int
language plpgsql security definer set search_path = ''
as $$
declare
  r record;
  n int := 0;
begin
  for r in
    select i.id, i.due_at from public.incidents i
     where i.wf_state is not null and i.wf_state not in ('done', 'cancelled', 'repaired') and i.due_at < now() and not i.by_test_account
  loop
    insert into public.alert_log (kind, key) values ('incident_due', 'incdue|' || r.id || '|' || r.due_at) on conflict (key) do nothing;
    if found then
      perform public.add_notify_event('incident', 'incidents', r.id, true, jsonb_build_object('event', 'overdue', 'due_at', r.due_at),
                                      'inc|' || r.id || '|overdue');
      n := n + 1;
    end if;
  end loop;
  return n;
end $$;
revoke execute on function public.check_incident_due() from public, anon, authenticated;

do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule('check-incident-due', '5 * * * *', 'select public.check_incident_due()');
  end if;
end $$;
