-- photos / videos added later are part of the history too
create or replace function public.incident_log_attachment() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.incident_id is not null and exists (select 1 from public.incidents i where i.id = new.incident_id and i.wf_state is not null)
     and exists (select 1 from public.incident_events e where e.incident_id = new.incident_id and e.at < new.created_at - interval '2 minutes') then
    insert into public.incident_events (incident_id, actor_id, actor_name, kind, action, data)
    values (new.incident_id, new.owner_id, coalesce((select coalesce(nullif(btrim(full_name), ''), display_name) from public.profiles where id = new.owner_id), '—'),
            'attachment', new.kind, jsonb_build_object('attachment_id', new.id));
  end if;
  return new;
end $$;
drop trigger if exists attachments_incident_event on public.attachments;
create trigger attachments_incident_event after insert on public.attachments for each row execute function public.incident_log_attachment();

