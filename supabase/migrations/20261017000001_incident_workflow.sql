create or replace function public.incident_log_created() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.wf_state is not null then
    insert into public.incident_events (incident_id, actor_id, actor_name, kind, action, to_state, data)
    values (new.id, new.reporter_id, new.reporter_name, 'created', 'report', new.wf_state,
            jsonb_build_object('priority', new.priority, 'due_at', new.due_at));
  end if;
  return new;
end $$;
