-- クレーム・事故の記録 Workflow V2, stage 1 = 設備の故障 (owner, 2026-10-16; plan artifact 6FGQX1MqKuGufAz9ukmNcb).
-- Additive only: incidents keeps every column and the old status (now derived from wf_state for workflow rows),
-- so the dashboard, the AI report, the mails and the backup keep working. Other kinds keep the old handling until
-- stage 3.
--  * incidents: 受付番号, wf_state, priority, assignee, due_at, discovered_at, occurred_known, acknowledged_at,
--    repaired_at, closed_at / closed_by, equipment, cause, cancel_reason, version (lost-update guard)
--  * incident_events: the append-only history (state / assign / comment / attachment …); no one may update or delete
--  * equipment_registry: equipment per store (設定 → 設備の一覧)
--  * incident_costs: 修理費用, managers only
--  * incident_act(): every workflow action, with the transition table, roles and the version check in the database
--  * staff see every 設備の故障 of both stores (staff work at both; shift handover), other kinds stay reporter + managers
--  * check_incident_due(): overdue → one urgent mail per due date (pg_cron hourly)

create table if not exists public.equipment_registry (
  id uuid primary key default gen_random_uuid(),
  store_id uuid not null references public.stores (id),
  name text not null check (char_length(btrim(name)) between 1 and 60),
  code text check (char_length(code) <= 40),
  category text not null default 'other' check (category in ('kitchen', 'ticket', 'aircon', 'fridge', 'water', 'electric', 'other')),
  note text check (char_length(note) <= 200),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
