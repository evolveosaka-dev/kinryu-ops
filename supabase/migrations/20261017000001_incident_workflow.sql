/** Default due date by priority: 緊急 24 h, 高 3 days, 通常 7 days (managers change it). */
create or replace function public.incident_default_due(p_priority text, p_from timestamptz) returns timestamptz
language sql immutable set search_path = ''
as $$ select p_from + case p_priority when 'urgent' then interval '24 hours' when 'high' then interval '3 days' else interval '7 days' end $$;

/** New 設備の故障 rows start the workflow: 報告済み, discovered = occurred when not given, a due date, a created event. */
create or replace function public.incident_wf_defaults() returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.kind = 'equipment' and new.wf_state is null then
    new.wf_state := 'reported';
    new.discovered_at := coalesce(new.discovered_at, new.occurred_at);
    new.due_at := coalesce(new.due_at, public.incident_default_due(new.priority, now()));
  end if;
  return new;
end $$;
drop trigger if exists incidents_wf_defaults on public.incidents;
create trigger incidents_wf_defaults before insert on public.incidents for each row execute function public.incident_wf_defaults();

